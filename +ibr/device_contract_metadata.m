function meta = eecon49_dual_source_state_metadata()
%EECON49_DUAL_SOURCE_STATE_METADATA  Shared-plant 17-state GFL/GFM contract.
%   Same device_type and controller blocks as the 16-state contract, with the
%   DC-source current appended as an explicit plant coordinate at index 17.
%   The model (ibr.eecon49_dual_mode_model) appends this state after the two
