function meta = device_contract_metadata(dev)
%DEVICE_CONTRACT_METADATA  Strict IBR-owned Section H state/input metadata registry.
%
%   meta = ibr.device_contract_metadata(dev) returns the frozen Section H
%   metadata (state_symbol, equation_source, equation_classification, unit,
%   frame, state_branch) for a supported IBR device struct. The function is
%   a PURE lookup keyed by the immutable (device_type, nx, nu, state_names,
%   input_names) identity of the device. It does NOT call dev.f,
%   current_injection, equilibrium_initialize, any equilibrium solver, SSSA,
%   or any external routine. It invents no equations, no parameters, and no
%   page citations.
%
%   This registry exists because the shared builder
%   (+stability/build_mixed_resource_devices.m) vertically concatenates
%   heterogeneous SG and IBR device structs, so IBR-only top-level fields
%   cannot be attached to the device struct without breaking mixed SG/IBR
%   construction. The registry is the IBR-owned, single-source-of-truth
%   metadata layer consumed by ibr.state_inventory_snapshot.
%
%   Supported contracts (exact-match dispatch):
%     'gfl_rms10'                device_type='ibr_gfl_rms10',     nx=10, nu=2
%     'eecon49_dual'             device_type='ibr_eecon49_dual', nx=16, nu=3
%     'eecon49_dual_source_state' device_type='ibr_eecon49_dual', nx=17, nu=3
%       (the 16 controller/plant states plus the DC-source current I_dc
%        appended at plant index 17 when source_state is enabled; the DC state
%        is carried explicitly, never dropped and never merged into 16)
%
%   Retired 2026-10-08 with their model families: 'gfm_regfm_b1'
%   (device_type='ibr_gfm', 13-state, REGFM_B1) and 'gfl_wecc_regca_reeca'
%   (device_type='ibr_gfl_wecc_regca_reeca', 7-state, WECC). No surviving
%   device publishes those device_types, so the registry no longer carries them.
%
%   Unknown device_type, wrong nx/nu, reordered/duplicate state_names, or
%   mismatched input_names fail closed with stable ibr:device_contract_metadata:*
%   identifiers. No WECC state is ever labelled as a PLL state.
%
%   Citation policy: every remaining contract's equation_source strings carry
%   page+equation citations frozen in docs/project/ (EECON49 GFL/GFM source
%   contract, EECON49-P4 Eqs.(6)-(29); GFL-RMS10 PROJECT_DERIVED composite).
%   No page citation is invented where the source is only established at block
%   level.
%
%   See: docs/project/IEEE14_IBR_DYNAMIC_EQUATION_CONTRACT.md (Section H).
%   Status: SOURCE_IMPLEMENTED_PENDING_INTEGRATION_GATES. Read-only metadata
%   layer; no production numerical equation, state order, or ABI change.

arguments
    dev struct
end

if ~isfield(dev,'device_type') || ~isfield(dev,'nx') || ~isfield(dev,'nu') ...
        || ~isfield(dev,'state_names') || ~isfield(dev,'input_names')
    error('ibr:device_contract_metadata:badDevice', ...
        'dev must have device_type, nx, nu, state_names, input_names.');
end

state_names = cellstr(string(dev.state_names));
input_names = cellstr(string(dev.input_names));
device_type = char(dev.device_type);

if strcmp(device_type,'ibr_gfl_rms10') && dev.nx == 10 && ...
        dev.nu == 2 && isequal(state_names, gfl_rms10_state_names()) && ...
        isequal(input_names, {'P_ref','Q_ref'})
    meta = gfl_rms10_metadata();
elseif strcmp(device_type,'ibr_eecon49_dual') && dev.nx == 16 && dev.nu == 3 && ...
        isequal(state_names, eecon49_dual_state_names()) && ...
        isequal(input_names, {'P_ref','Q_ref','E_ref'})
    meta = eecon49_dual_metadata();
elseif strcmp(device_type,'ibr_eecon49_dual') && dev.nx == 17 && dev.nu == 3 && ...
        isequal(state_names, eecon49_dual_source_state_names()) && ...
        isequal(input_names, {'P_ref','Q_ref','E_ref'})
    meta = eecon49_dual_source_state_metadata();
else
    error('ibr:device_contract_metadata:unknownContract', ...
        ['Unknown IBR device contract: device_type=%s nx=%d nu=%d. ' ...
         'Registry supports ibr_gfl_rms10(10,2), ibr_eecon49_dual(16,3), ' ...
         'ibr_eecon49_dual(17,3) with exact state/input order.'], ...
        device_type, dev.nx, dev.nu);
end
end

