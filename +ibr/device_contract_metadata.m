    'I_dc','I_dc',sprintf(['%s: project DC current-source regulator plant ' ...
    'coordinate (appended at superset index 17 when source_state is enabled)'],doc), ...
    'PROJECT_DERIVED','pu dc current','dc link','common', ...
    'PAGE_LEVEL_PLUS_PROJECT_DERIVATION',src});
meta.contract_id = 'eecon49_dual_source_state';
meta.contract_version = 'production_r1_source_state';
end

