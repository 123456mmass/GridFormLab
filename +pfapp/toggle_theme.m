function app = toggle_theme(app, fig)
%TOGGLE_THEME Switch between light and dark themes by rebuilding in place.
%   The whole interface is re-created inside the existing figure so that
%   every widget picks up the new palette, the live app/fig references stay
%   valid, and the currently displayed result is re-rendered afterwards.

if strcmp(app.theme_mode, 'light')
    app.theme_mode = 'dark';
else
    app.theme_mode = 'light';
end
app.theme = build_theme(app.theme_mode);

% Persist preference before rebuild (save_preferences reads app.theme_mode).
pfapp.save_preferences(app);

% Rebuild the layout inside the existing figure (create_gui_layout clears
% fig.Children when app.fig is valid) and re-wire every callback.
[fig, app] = pfapp.create_gui_layout(app);
app.fig = fig;
fig.UserData.app = app;
pfapp.wire_callbacks(app, fig);

% Re-display whatever result was on screen before the theme swap.
pfapp.refresh_display(app);

pfapp.append_log(app, sprintf('Theme switched to %s mode.', app.theme_mode));
end

