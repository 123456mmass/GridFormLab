function show_suite_result(app, suite)
%SHOW_SUITE_RESULT Display full-suite comparison in table and plots.

axis_info = pf_bus_axis_info(suite.newton_raphson.external_bus_ids);
data = table( ...
    ["Newton-Raphson"; "Gauss-Seidel"; "CPF Load Scaling"; "CPF Predictor-Corrector"], ...
    [suite.newton_raphson.converged; suite.gauss_seidel.converged; suite.cpf_load_scaling.converged; suite.cpf_predictor_corrector.converged], ...
    [suite.newton_raphson.iterations; suite.gauss_seidel.iterations; numel(suite.cpf_load_scaling.lambdas); numel(suite.cpf_predictor_corrector.lambdas)], ...
    [suite.newton_raphson.P_loss_total; suite.gauss_seidel.P_loss_total; NaN; NaN], ...
    'VariableNames', {'Method', 'Converged', 'Iterations_or_Points', 'P_loss_pu'});
app.result_table.Data = data;
pfapp.style_result_table(app, 'suite');
pfapp.update_dashboard_metrics(app, ...
    {'SUITE', 'NR ITER', 'GS ITER', 'CPF POINTS'}, ...
    {'Done', sprintf('%d', suite.newton_raphson.iterations), sprintf('%d', suite.gauss_seidel.iterations), sprintf('%d / %d', numel(suite.cpf_load_scaling.lambdas), numel(suite.cpf_predictor_corrector.lambdas))}, ...
    {'5-bus comparison', sprintf('P loss %.4f pu', suite.newton_raphson.P_loss_total), sprintf('P loss %.4f pu', suite.gauss_seidel.P_loss_total), 'LS / PC'}, ...
    {[0.18 0.50 0.32], [0.02 0.44 0.62], [0.86 0.38 0.13], [0.45 0.30 0.72]});

pfapp.reset_axes_state(app.ax_voltage);
plot(app.ax_voltage, axis_info.x, suite.newton_raphson.bus_voltage, '-o', ...
    axis_info.x, suite.gauss_seidel.bus_voltage, '-s', 'LineWidth', 1.8);
title(app.ax_voltage, 'NR vs GS Voltage');
xlabel(app.ax_voltage, axis_info.xlabel);
ylabel(app.ax_voltage, '|V| pu');
legend(app.ax_voltage, {'NR', 'GS'}, 'Location', 'best');
grid(app.ax_voltage, 'on');
if ~isempty(axis_info.note)
    text(app.ax_voltage, 0.01, 0.96, axis_info.note, 'Units', 'normalized', ...
        'HorizontalAlignment', 'left', 'VerticalAlignment', 'top', ...
        'FontSize', 8, 'Color', [0.30 0.30 0.30]);
end

pfapp.reset_axes_state(app.ax_conv);
semilogy(app.ax_conv, 1:numel(suite.newton_raphson.mismatch_history), suite.newton_raphson.mismatch_history, '-o', ...
    1:numel(suite.gauss_seidel.mismatch_history), suite.gauss_seidel.mismatch_history, '-s', 'LineWidth', 1.6);
title(app.ax_conv, 'NR vs GS Convergence');
xlabel(app.ax_conv, 'Iteration');
ylabel(app.ax_conv, 'Max mismatch');
legend(app.ax_conv, {'NR', 'GS'}, 'Location', 'best');
grid(app.ax_conv, 'on');
end
