function app = toggle_theme(app, fig)
%TOGGLE_THEME Switch between light and dark themes.

if strcmp(app.theme_mode, 'light')
    app.theme_mode = 'dark';
    app.theme = build_theme('dark');
    app.theme_toggle.Text = "Light Mode";
else
    app.theme_mode = 'light';
    app.theme = build_theme('light');
    app.theme_toggle.Text = "Dark Mode";
end

% Save preference
pfapp.save_preferences(app);

% Rebuild the GUI with new theme
[~, app] = pfapp.create_gui_layout(app);
app.theme_mode = app.theme_mode;

% Re-wire callbacks (nested in run_powerflow_gui)
% The caller must re-wire. For standalone, just update colors:
update_fig_colors(fig, app.theme);
pfapp.append_log(app, sprintf('Theme switched to %s mode', app.theme_mode));

    function update_fig_colors(f, t)
        f.Color = t.canvas;
        kids = findall(f, '-property', 'BackgroundColor');
        for k = 1:numel(kids)
            c = kids(k).BackgroundColor;
            if isequal(c, [0.945 0.955 0.965]) || isequal(c, [0.08 0.09 0.11])
                kids(k).BackgroundColor = t.canvas;
            elseif isequal(c, [1 1 1]) || isequal(c, [0.14 0.15 0.17])
                kids(k).BackgroundColor = t.surface;
            elseif isequal(c, [0.965 0.970 0.980]) || isequal(c, [0.18 0.19 0.22])
                kids(k).BackgroundColor = t.surface_alt;
            end
        end
    end
end

