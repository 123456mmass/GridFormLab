function paths = pf_export_opf_results(results, output_dir, file_prefix)
%PF_EXPORT_OPF_RESULTS Export OPF dispatch and optional AC network results.

if nargin < 2 || isempty(output_dir)
    output_dir = fullfile(pwd, 'output');
end
if nargin < 3 || isempty(file_prefix)
    file_prefix = make_safe_name(sprintf('%s_%s', results.system_name, results.method));
end
if ~exist(output_dir, 'dir')
    mkdir(output_dir);
end

csv_file = fullfile(output_dir, [file_prefix '_opf_dispatch.csv']);
summary_txt = fullfile(output_dir, [file_prefix '_opf_summary.txt']);

if isfield(results, 'Q_generation_MVAr')
    dispatch_table = table( ...
        results.generator_ids(:), ...
        results.generator_bus_ids(:), ...
        results.P_generation_MW(:), ...
        results.Q_generation_MVAr(:), ...
        results.incremental_cost(:), ...
        results.generator_cost(:), ...
        results.P_min_MW(:), ...
        results.P_max_MW(:), ...
        results.Q_min_MVAr(:), ...
        results.Q_max_MVAr(:), ...
        results.active_limits(:), ...
        'VariableNames', {'Generator', 'Bus', 'P_MW', 'Q_MVAr', ...
        'IncrementalCost_per_MWh', 'Cost_per_h', 'Pmin_MW', 'Pmax_MW', ...
        'Qmin_MVAr', 'Qmax_MVAr', 'ActiveLimit'});
else
    dispatch_table = table( ...
        results.generator_ids(:), ...
        results.P_generation_MW(:), ...
        results.incremental_cost(:), ...
        results.generator_cost(:), ...
        results.P_min_MW(:), ...
        results.P_max_MW(:), ...
        results.active_limits(:), ...
        'VariableNames', {'Generator', 'P_MW', 'IncrementalCost_per_MWh', ...
        'Cost_per_h', 'Pmin_MW', 'Pmax_MW', 'ActiveLimit'});
end
writetable(dispatch_table, csv_file);

paths = struct('dispatch_csv', csv_file, 'summary_txt', summary_txt);

if isfield(results, 'bus_voltage')
    bus_csv = fullfile(output_dir, [file_prefix '_opf_bus_results.csv']);
    bus_table = table( ...
        results.external_bus_ids(:), ...
        results.bus_voltage(:), ...
        results.bus_angle_deg(:), ...
        results.P_generation(:) * results.base_values.S_base_MVA, ...
        results.Q_generation(:) * results.base_values.S_base_MVA, ...
        results.P_load(:) * results.base_values.S_base_MVA, ...
        results.Q_load(:) * results.base_values.S_base_MVA, ...
        results.V_min(:), ...
        results.V_max(:), ...
        'VariableNames', {'Bus', 'V_pu', 'Angle_deg', 'Pgen_MW', ...
        'Qgen_MVAr', 'Pload_MW', 'Qload_MVAr', 'Vmin_pu', 'Vmax_pu'});
    writetable(bus_table, bus_csv);
    paths.bus_csv = bus_csv;
end

if isfield(results, 'line_from_MVA')
    line_csv = fullfile(output_dir, [file_prefix '_opf_line_results.csv']);
    if isempty(results.line_loading_percent)
        loading = nan(size(results.line_from_MVA));
    else
        loading = results.line_loading_percent(:);
    end
    if isempty(results.S_line_max_MVA)
        limits = nan(size(results.line_from_MVA));
    else
        limits = results.S_line_max_MVA(:);
    end
    line_table = table( ...
        results.line_endpoints(:, 1), ...
        results.line_endpoints(:, 2), ...
        results.line_from_MVA(:), ...
        results.line_to_MVA(:), ...
        limits, ...
        loading, ...
        'VariableNames', {'From', 'To', 'S_from_MVA', 'S_to_MVA', ...
        'Limit_MVA', 'Loading_percent'});
    writetable(line_table, line_csv);
    paths.line_csv = line_csv;
end

fid = fopen(summary_txt, 'w');
if fid < 0
    error('Could not open %s for writing.', summary_txt);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s Summary\n', results.method);
fprintf(fid, 'System: %s\n', results.system_name);
fprintf(fid, 'Equivalent buses: %d\n', results.equivalent_bus_count);
fprintf(fid, 'Demand: %.8f MW\n', results.P_demand_MW);
if isfield(results, 'Q_demand_MVAr')
    fprintf(fid, 'Reactive demand: %.8f MVAr\n', results.Q_demand_MVAr);
end
fprintf(fid, 'Lambda/mean incremental cost: %.8f $/MWh\n', results.lambda);
fprintf(fid, 'Total cost: %.8f $/h\n', results.total_cost);
if isfield(results, 'max_power_balance_mismatch')
    fprintf(fid, 'Generation minus demand: %.8f MW\n', sum(results.P_generation_MW) - results.P_demand_MW);
    if isfield(results, 'P_loss_total')
        fprintf(fid, 'Network real-power loss: %.8f MW\n', results.P_loss_total * results.base_values.S_base_MVA);
    end
    fprintf(fid, 'Max AC power-balance mismatch: %.8e pu\n', results.max_power_balance_mismatch);
else
    fprintf(fid, 'Balance residual: %.8e MW\n', sum(results.P_generation_MW) - results.P_demand_MW);
end
if isfield(results, 'line_loading_percent') && ~isempty(results.line_loading_percent)
    fprintf(fid, 'Max line loading: %.8f %%\n', max(results.line_loading_percent));
end
end

function safe_name = make_safe_name(name)
safe_name = regexprep(char(name), '[^A-Za-z0-9_]+', '_');
safe_name = regexprep(safe_name, '_+', '_');
safe_name = regexprep(safe_name, '^_|_$', '');
end
