function write_cross_case(rows, path)
fid = fopen(path,'w'); z = onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid, '%% Generated by report_table_helpers. Do not edit by hand.\n');
fprintf(fid, '\\begin{longtable}{lrrrrr l}\\toprule\n');
fprintf(fid, 'Case & PF max mismatch & PF ext. err & Dominant mode & TS bounded & Fixed/Adaptive diff & Status \\\\ \\midrule\n');
for i = 1:numel(rows)
    r = rows(i);
    fprintf(fid, '%s & %.2e & %.2e & %s & %s & %.2e & %s \\\\\n', ...
        r.case_name, r.pf_max_mismatch, r.pf_ext_err, r.dominant_mode, ...
        r.ts_bounded, r.fa_diff, r.status);
end
fprintf(fid, '\\bottomrule\n\\end{longtable}\n');
end

function write_input_contract(fp, path)
fid = fopen(path,'w'); z = onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid, '%% Generated by report_table_helpers. Do not edit by hand.\n');
fprintf(fid, '\\begin{tabular}{ll}\\toprule Field & Value \\\\ \\midrule\n');
fns = fieldnames(fp);
for i = 1:numel(fns)
    v = fp.(fns{i});
    if isnumeric(v), v = mat2str(v(:).'); end
    if ischar(v) && strlen(v) > 60, v = [v(1:60) '...']; end
    fprintf(fid, '%s & %s \\\\\n', strrep(fns{i},'_','\\_'), v);
end
fprintf(fid, '\\bottomrule\n\\end{tabular}\n');
end

