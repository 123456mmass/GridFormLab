function report_table_helpers(action, varargin)
%REPORT_TABLE_HELPERS  Shared LaTeX table writers for the report generator.
%   report_table_helpers('pf_bus', data, path, caption) writes a PF bus-by-bus
%   comparison table. All tables are generated programmatically from data;
%   no computed value is typed manually.
%
%   Actions: pf_bus, pf_summary, machine_params, fault_event, sssa_eig,
%   ts_metrics, fixed_adaptive_diag, cross_case, input_contract.

switch lower(action)
case 'pf_bus'
    write_pf_bus(varargin{:});
case 'pf_summary'
    write_pf_summary(varargin{:});
case 'machine_params'
    write_machine_params(varargin{:});
case 'fault_event'
    write_fault_event(varargin{:});
case 'sssa_eig'
    write_sssa_eig(varargin{:});
case 'ts_metrics'
    write_ts_metrics(varargin{:});
case 'fixed_adaptive_diag'
    write_fixed_adaptive_diag(varargin{:});
case 'cross_case'
    write_cross_case(varargin{:});
case 'input_contract'
    write_input_contract(varargin{:});
otherwise
    error('report_table_helpers:unknownAction','Unknown action: %s',action);
end
end

function write_pf_bus(bus_ids, vm_ours, va_ours, vm_ref, va_ref, ref_label, path)
fid = fopen(path,'w'); z = onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid, '%% Generated by report_table_helpers. Do not edit by hand.\n');
fprintf(fid, '\\begin{longtable}{r rrr rrr}\\toprule\n');
fprintf(fid, '{Bus} & {$|V|_{ours}$} & {$|V|_{%s}$} & {$|\\Delta V|$} & {$\\theta_{ours}$} & {$\\theta_{%s}$} & {$|\\Delta\\theta|$} \\\\\n', ref_label, ref_label);
fprintf(fid, '{} & {(pu)} & {(pu)} & {(pu)} & {(deg)} & {(deg)} & {(deg)} \\\\ \\midrule\n');
for k = 1:numel(bus_ids)
    dV = abs(vm_ours(k) - vm_ref(k));
    dA = abs(va_ours(k) - va_ref(k));
    fprintf(fid, '%g & %.6f & %.6f & %.2e & %.6f & %.6f & %.2e \\\\\n', ...
        bus_ids(k), vm_ours(k), vm_ref(k), dV, va_ours(k), va_ref(k), dA);
end
fprintf(fid, '\\bottomrule\n\\end{longtable}\n');
end

function write_pf_summary(summary, path)
fid = fopen(path,'w'); z = onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid, '%% Generated by report_table_helpers. Do not edit by hand.\n');
fprintf(fid, '\\begin{tabular}{lr}\\toprule Quantity & Value \\\\ \\midrule\n');
fns = fieldnames(summary);
for i = 1:numel(fns)
    v = summary.(fns{i});
    if isnumeric(v), v = num2str(v, '%.6g'); end
    fprintf(fid, '%s & %s \\\\\n', strrep(fns{i},'_','\\_'), v);
end
fprintf(fid, '\\bottomrule\n\\end{tabular}\n');
end

function write_machine_params(gen_buses, H, D, Xdp, source, path)
fid = fopen(path,'w'); z = onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid, '%% Generated by report_table_helpers. Do not edit by hand.\n');
fprintf(fid, '\\begin{tabular}{r llll l}\\toprule\n');
fprintf(fid, '{Bus} & {$H$} & {$D$} & {$X''_d$} & {Source} \\\\ \n');
fprintf(fid, '{} & {(s)} & {(pu)} & {(pu)} & {} \\\\ \\midrule\n');
for k = 1:numel(gen_buses)
    src = ''; if numel(source) >= k, src = source{k}; end
    fprintf(fid, '%g & %.4f & %.4f & %.4f & %s \\\\\n', ...
        gen_buses(k), H(k), D(k), Xdp(k), src);
end
fprintf(fid, '\\bottomrule\n\\end{tabular}\n');
end

