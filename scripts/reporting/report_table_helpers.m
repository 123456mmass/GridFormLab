function write_sssa_eig(eigs_ours, eigs_ref, ref_label, path)
fid = fopen(path,'w'); z = onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid, '%% Generated by report_table_helpers. Do not edit by hand.\n');
fprintf(fid, '\\begin{longtable}{r cc cc ll}\\toprule\n');
fprintf(fid, 'No. & {$\\lambda_{ours}$} & {$\\lambda_{%s}$} & {$f_{ours}$ (Hz)} & {$\\zeta_{ours}$ (\\%%)} & Mode \\\\ \\midrule\n', ref_label);
n = max(numel(eigs_ours), numel(eigs_ref));
for k = 1:n
    lo = eigs_ours(k); lr = eigs_ref(k);
    fo = abs(imag(lo))/(2*pi); zo = -real(lo)/(abs(lo)+eps)*100;
    if abs(imag(lo))<1e-9, so = sprintf('%.4f',real(lo)); else, so = sprintf('%.4f%+.4fj',real(lo),imag(lo)); end
    if abs(imag(lr))<1e-9, sr = sprintf('%.4f',real(lr)); else, sr = sprintf('%.4f%+.4fj',real(lr),imag(lr)); end
    fprintf(fid, '%d & $%s$ & $%s$ & %.4f & %.3f & \\\\\n', k, so, sr, fo, zo);
end
fprintf(fid, '\\bottomrule\n\\end{longtable}\n');
end

